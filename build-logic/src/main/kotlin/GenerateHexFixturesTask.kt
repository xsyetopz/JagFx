import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Embeds every `*.[extension]` file of [sourceDir] as a hex string in a generated Kotlin object,
 * so common tests read the same fixtures on every target without platform file I/O.
 */
@CacheableTask
abstract class GenerateHexFixturesTask : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sourceDir: DirectoryProperty

    @get:Input
    abstract val extension: Property<String>

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val objectName: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val files =
            sourceDir
                .get()
                .asFile
                .listFiles { file -> file.isFile && file.extension == extension.get() }
                .orEmpty()
                .sortedBy { it.name }
        val entries =
            files.joinToString(separator = "") { file ->
                val hex = file.readBytes().joinToString(separator = "") { "%02x".format(it) }
                "        \"${file.nameWithoutExtension}\" to \"$hex\",\n"
            }
        val source =
            buildString {
                append(
                    "// Generated by ${GenerateHexFixturesTask::class.simpleName}. Do not edit.\n",
                )
                append("package ${packageName.get()}\n\n")
                append("internal object ${objectName.get()} {\n")
                append("    val hex: Map<String, String> = mapOf(\n")
                append(entries)
                append("    )\n")
                append("}\n")
            }
        val packageDir = outputDir.get().asFile.resolve(packageName.get().replace('.', '/'))
        outputDir.get().asFile.deleteRecursively()
        packageDir.mkdirs()
        packageDir.resolve("${objectName.get()}.kt").writeText(source)
    }
}
